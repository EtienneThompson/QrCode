import { defineConfig, loadEnv, type Plugin } from "vite";
import react from "@vitejs/plugin-react";

// In dev, proxy QR Tracker API routes to api.etiennethompson.com running locally (`yarn dev`).
const api = "http://localhost:4000";

/**
 * Emits an Apache .htaccess that forwards scan links on the website's own domain
 * (https://<site>/r/<id>) to the API's /qr/r/<id>, which records the scan and redirects on.
 * Lets QR_PUBLIC_BASE_URL be the website's address, so QR codes carry your domain.
 */
function scanLinkRedirect(apiBaseUrl: string | undefined): Plugin {
  return {
    name: "scan-link-redirect",
    apply: "build",
    generateBundle() {
      if (!apiBaseUrl) return;
      const target = apiBaseUrl.replace(/\/+$/, "");
      this.emitFile({
        type: "asset",
        fileName: ".htaccess",
        source: [
          "# Generated by web/vite.config.ts from VITE_API_BASE_URL.",
          "# Scan links /r/<id> go to the QR Tracker API, which records the scan and redirects.",
          "RewriteEngine On",
          `RewriteRule ^r/([0-9A-Za-z]{1,32})/?$ ${target}/qr/r/$1 [R=302,L]`,
          "",
        ].join("\n"),
      });
    },
  };
}

export default defineConfig(({ mode }) => ({
  plugins: [react(), scanLinkRedirect(loadEnv(mode, process.cwd(), "VITE_").VITE_API_BASE_URL)],
  // Relative asset paths, so the built site works from any folder (e.g. example.com/qr/).
  base: "./",
  // A distinctive folder name: deploy-web.sh prunes old files in it on the server.
  build: { assetsDir: "qr-assets" },
  server: {
    // Regex keys, so /qr-assets/… isn't proxied.
    proxy: {
      "^/qr/": api,
    },
  },
}));
